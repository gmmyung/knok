#[macro_export]
/// Includes graph wrapper modules generated by `knok-build` into the target crate.
macro_rules! generated_graphs {
    () => {
        include!(concat!(env!("OUT_DIR"), "/knok_graphs.rs"));
    };
    ($file:literal) => {
        include!(concat!(env!("OUT_DIR"), "/", $file));
    };
    (mod $name:ident) => {
        mod $name {
            include!(concat!(env!("OUT_DIR"), "/knok_graphs.rs"));
        }
    };
    (mod $name:ident, $file:literal) => {
        mod $name {
            include!(concat!(env!("OUT_DIR"), "/", $file));
        }
    };
    (pub mod $name:ident) => {
        pub mod $name {
            include!(concat!(env!("OUT_DIR"), "/knok_graphs.rs"));
        }
    };
    (pub mod $name:ident, $file:literal) => {
        pub mod $name {
            include!(concat!(env!("OUT_DIR"), "/", $file));
        }
    };
}

